CREATE TABLE chat_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id VARCHAR(44) NOT NULL REFERENCES guest_session(id) ON DELETE CASCADE,
    request_id UUID NOT NULL,
    message_hash VARCHAR(64) NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('IN_PROGRESS','COMPLETED','FAILED')),
    attempt_token UUID NOT NULL,
    lease_expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    error_code VARCHAR(80),
    response_json JSONB,
    CONSTRAINT uk_chat_request_session_request UNIQUE(session_id, request_id)
);
CREATE UNIQUE INDEX uk_chat_request_active_session ON chat_request(session_id) WHERE status = 'IN_PROGRESS';
CREATE TABLE chat_message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id VARCHAR(44) NOT NULL REFERENCES guest_session(id) ON DELETE CASCADE,
    request_id UUID NOT NULL,
    role VARCHAR(10) NOT NULL CHECK (role IN ('USER','ASSISTANT')),
    content TEXT NOT NULL,
    metadata_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    FOREIGN KEY(session_id, request_id) REFERENCES chat_request(session_id, request_id) ON DELETE CASCADE,
    CONSTRAINT uk_chat_message_request_role UNIQUE(session_id, request_id, role)
);
CREATE INDEX idx_chat_message_session_id ON chat_message(session_id, id DESC);
