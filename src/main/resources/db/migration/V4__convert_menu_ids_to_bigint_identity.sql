-- Preserve existing menu data and cart references. V2/V3 have already been applied.
-- Flyway runs this migration transactionally; block writes while keys are replaced.
LOCK TABLE menu_item, cart_item IN ACCESS EXCLUSIVE MODE;

ALTER TABLE menu_item ADD COLUMN new_id BIGINT;

-- Keep the sample menu IDs predictable, even if other dishes have been added.
UPDATE menu_item SET new_id = CASE id
    WHEN '00000000-0000-4000-8000-000000000001'::uuid THEN 1
    WHEN '00000000-0000-4000-8000-000000000002'::uuid THEN 2
    WHEN '00000000-0000-4000-8000-000000000003'::uuid THEN 3
    WHEN '00000000-0000-4000-8000-000000000004'::uuid THEN 4
    WHEN '00000000-0000-4000-8000-000000000005'::uuid THEN 5
    WHEN '00000000-0000-4000-8000-000000000006'::uuid THEN 6
END;

WITH remaining_items AS (
    SELECT id, 6 + row_number() OVER (ORDER BY id) AS new_id
    FROM menu_item
    WHERE new_id IS NULL
)
UPDATE menu_item AS menu SET new_id = remaining.new_id
FROM remaining_items AS remaining WHERE menu.id = remaining.id;

ALTER TABLE menu_item ALTER COLUMN new_id SET NOT NULL;
ALTER TABLE cart_item ADD COLUMN new_menu_item_id BIGINT;
UPDATE cart_item AS item SET new_menu_item_id = menu.new_id
FROM menu_item AS menu WHERE item.menu_item_id = menu.id;
ALTER TABLE cart_item ALTER COLUMN new_menu_item_id SET NOT NULL;

ALTER TABLE cart_item DROP CONSTRAINT cart_item_menu_item_id_fkey;
ALTER TABLE cart_item DROP CONSTRAINT uk_cart_item_cart_menu;
ALTER TABLE menu_item DROP CONSTRAINT menu_item_pkey;

ALTER TABLE menu_item DROP COLUMN id;
ALTER TABLE menu_item RENAME COLUMN new_id TO id;
ALTER TABLE menu_item ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE menu_item ADD CONSTRAINT menu_item_pkey PRIMARY KEY (id);

-- Advance the identity sequence past every migrated item, including custom dishes.
SELECT setval(pg_get_serial_sequence('menu_item', 'id'),
              GREATEST(COALESCE((SELECT max(id) FROM menu_item), 0), 1),
              EXISTS (SELECT 1 FROM menu_item));

ALTER TABLE cart_item DROP COLUMN menu_item_id;
ALTER TABLE cart_item RENAME COLUMN new_menu_item_id TO menu_item_id;
ALTER TABLE cart_item ADD CONSTRAINT cart_item_menu_item_id_fkey
    FOREIGN KEY (menu_item_id) REFERENCES menu_item (id);
ALTER TABLE cart_item ADD CONSTRAINT uk_cart_item_cart_menu UNIQUE (cart_id, menu_item_id);
